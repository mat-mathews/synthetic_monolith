    _cacheDuration = TimeSpan.FromMinutes(
        _configuration.GetValue<int>("Processor7:CacheDurationMinutes", 30));
}

/// <summary>
/// Gets or creates a cached Processor7 instance.
/// Uses IMemoryCache with sliding expiration.
/// </summary>
public async Task<Processor7Data> GetCachedProcessor7Async(string key)
{
    var cacheKey = $"Processor7_{key}";

    if (_cache.TryGetValue(cacheKey, out Processor7Data cached))
    {
        _logger.LogDebug("Cache hit for {Key}", cacheKey);
        return cached;
    }

    _logger.LogDebug("Cache miss for {Key}, loading from source", cacheKey);

    var data = await LoadFromProcessor7SourceAsync(key);

    var cacheOptions = new MemoryCacheEntryOptions()
        .SetSlidingExpiration(_cacheDuration)
        .SetAbsoluteExpiration(TimeSpan.FromHours(4));

    _cache.Set(cacheKey, data, cacheOptions);
    return data;
}

