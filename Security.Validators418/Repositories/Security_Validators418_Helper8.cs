        scope.Complete();

        _logger.LogInformation("Successfully processed {Operation}", nameof(Helper8));
        return new Helper8Result { Success = true, Data = entity };
    }
    catch (DbUpdateConcurrencyException ex)
    {
        _logger.LogError(ex, "Concurrency conflict processing {Operation}", nameof(Helper8));
        return new Helper8Result { Success = false, ErrorCode = "CONCURRENCY_CONFLICT" };
    }
