        scope.Complete();

        _logger.LogInformation("Successfully processed {Operation}", nameof(Helper13));
        return new Helper13Result { Success = true, Data = entity };
    }
    catch (DbUpdateConcurrencyException ex)
    {
        _logger.LogError(ex, "Concurrency conflict processing {Operation}", nameof(Helper13));
        return new Helper13Result { Success = false, ErrorCode = "CONCURRENCY_CONFLICT" };
    }
