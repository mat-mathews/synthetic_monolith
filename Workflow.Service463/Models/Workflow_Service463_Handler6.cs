/// <summary>
/// Gets or creates a cached Handler6 instance.
/// Uses IMemoryCache with sliding expiration.
/// </summary>
public async Task<Handler6Data> GetCachedHandler6Async(string key)
{
    var cacheKey = $"Handler6_{key}";

    if (_cache.TryGetValue(cacheKey, out Handler6Data cached))
    {
        _logger.LogDebug("Cache hit for {Key}", cacheKey);
        return cached;
    }

    _logger.LogDebug("Cache miss for {Key}, loading from source", cacheKey);

    var data = await LoadFromHandler6SourceAsync(key);

    var cacheOptions = new MemoryCacheEntryOptions()
        .SetSlidingExpiration(_cacheDuration)
        .SetAbsoluteExpiration(TimeSpan.FromHours(4));

    _cache.Set(cacheKey, data, cacheOptions);
    return data;
}

