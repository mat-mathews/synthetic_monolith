/// <summary>
/// Processes the Handler9 operation asynchronously.
/// </summary>
public async Task<Handler9Result> ProcessHandler9Async(
    Handler9Request request,
    CancellationToken cancellationToken = default)
{
    _logger.LogInformation("Processing {Operation} for {Id}",
        nameof(Handler9), request.Id);

    // Validate input parameters
    if (request == null)
        throw new ArgumentNullException(nameof(request));

    try
    {
