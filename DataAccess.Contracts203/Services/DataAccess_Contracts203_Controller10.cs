public async Task<Controller10Result> ProcessController10Async(
    Controller10Request request,
    CancellationToken cancellationToken = default)
{
    _logger.LogInformation("Processing {Operation} for {Id}",
        nameof(Controller10), request.Id);

    // Validate input parameters
    if (request == null)
