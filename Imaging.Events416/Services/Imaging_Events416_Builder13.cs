        scope.Complete();

        _logger.LogInformation("Successfully processed {Operation}", nameof(Builder13));
        return new Builder13Result { Success = true, Data = entity };
    }
    catch (DbUpdateConcurrencyException ex)
    {
        _logger.LogError(ex, "Concurrency conflict processing {Operation}", nameof(Builder13));
        return new Builder13Result { Success = false, ErrorCode = "CONCURRENCY_CONFLICT" };
    }
