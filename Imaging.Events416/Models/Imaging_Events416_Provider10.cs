        scope.Complete();

        _logger.LogInformation("Successfully processed {Operation}", nameof(Provider10));
        return new Provider10Result { Success = true, Data = entity };
    }
    catch (DbUpdateConcurrencyException ex)
    {
        _logger.LogError(ex, "Concurrency conflict processing {Operation}", nameof(Provider10));
        return new Provider10Result { Success = false, ErrorCode = "CONCURRENCY_CONFLICT" };
    }
