        scope.Complete();

        _logger.LogInformation("Successfully processed {Operation}", nameof(Provider8));
        return new Provider8Result { Success = true, Data = entity };
    }
    catch (DbUpdateConcurrencyException ex)
    {
        _logger.LogError(ex, "Concurrency conflict processing {Operation}", nameof(Provider8));
        return new Provider8Result { Success = false, ErrorCode = "CONCURRENCY_CONFLICT" };
    }
