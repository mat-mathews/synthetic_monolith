        scope.Complete();

        _logger.LogInformation("Successfully processed {Operation}", nameof(Provider13));
        return new Provider13Result { Success = true, Data = entity };
    }
    catch (DbUpdateConcurrencyException ex)
    {
        _logger.LogError(ex, "Concurrency conflict processing {Operation}", nameof(Provider13));
        return new Provider13Result { Success = false, ErrorCode = "CONCURRENCY_CONFLICT" };
    }
