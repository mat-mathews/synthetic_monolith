/// <returns>True if valid, false otherwise.</returns>
public bool ValidateController12(Controller12Request input)
{
    if (input == null)
        throw new ArgumentNullException(nameof(input));

    if (string.IsNullOrWhiteSpace(input.Name))
    {
        _logger.LogWarning("Validation failed: Name is required for {Type}", nameof(Controller12));
        return false;
