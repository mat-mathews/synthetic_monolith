/// <summary>
/// Processes the Controller1 operation asynchronously.
/// </summary>
public async Task<Controller1Result> ProcessController1Async(
    Controller1Request request,
    CancellationToken cancellationToken = default)
{
    _logger.LogInformation("Processing {Operation} for {Id}",
        nameof(Controller1), request.Id);

    // Validate input parameters
    if (request == null)
        throw new ArgumentNullException(nameof(request));

    try
    {
