        scope.Complete();

        _logger.LogInformation("Successfully processed {Operation}", nameof(Service2));
        return new Service2Result { Success = true, Data = entity };
    }
    catch (DbUpdateConcurrencyException ex)
    {
        _logger.LogError(ex, "Concurrency conflict processing {Operation}", nameof(Service2));
        return new Service2Result { Success = false, ErrorCode = "CONCURRENCY_CONFLICT" };
    }
