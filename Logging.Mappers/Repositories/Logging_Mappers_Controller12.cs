        scope.Complete();

        _logger.LogInformation("Successfully processed {Operation}", nameof(Controller12));
        return new Controller12Result { Success = true, Data = entity };
    }
    catch (DbUpdateConcurrencyException ex)
    {
        _logger.LogError(ex, "Concurrency conflict processing {Operation}", nameof(Controller12));
        return new Controller12Result { Success = false, ErrorCode = "CONCURRENCY_CONFLICT" };
    }
