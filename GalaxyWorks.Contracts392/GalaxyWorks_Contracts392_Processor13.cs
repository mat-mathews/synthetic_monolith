/// <returns>True if valid, false otherwise.</returns>
public bool ValidateProcessor13(Processor13Request input)
{
    if (input == null)
        throw new ArgumentNullException(nameof(input));

    if (string.IsNullOrWhiteSpace(input.Name))
    {
        _logger.LogWarning("Validation failed: Name is required for {Type}", nameof(Processor13));
        return false;
    }

    /* Multi-line validation logic:
