        scope.Complete();

        _logger.LogInformation("Successfully processed {Operation}", nameof(Manager8));
        return new Manager8Result { Success = true, Data = entity };
    }
    catch (DbUpdateConcurrencyException ex)
    {
        _logger.LogError(ex, "Concurrency conflict processing {Operation}", nameof(Manager8));
        return new Manager8Result { Success = false, ErrorCode = "CONCURRENCY_CONFLICT" };
    }
