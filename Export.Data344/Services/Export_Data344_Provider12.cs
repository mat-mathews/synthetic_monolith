        scope.Complete();

        _logger.LogInformation("Successfully processed {Operation}", nameof(Provider12));
        return new Provider12Result { Success = true, Data = entity };
    }
    catch (DbUpdateConcurrencyException ex)
    {
        _logger.LogError(ex, "Concurrency conflict processing {Operation}", nameof(Provider12));
        return new Provider12Result { Success = false, ErrorCode = "CONCURRENCY_CONFLICT" };
    }
