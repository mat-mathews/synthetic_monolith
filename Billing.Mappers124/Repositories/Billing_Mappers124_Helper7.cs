        return new Helper7Result { Success = true, Data = entity };
    }
    catch (DbUpdateConcurrencyException ex)
    {
        _logger.LogError(ex, "Concurrency conflict processing {Operation}", nameof(Helper7));
        return new Helper7Result { Success = false, ErrorCode = "CONCURRENCY_CONFLICT" };
    }
