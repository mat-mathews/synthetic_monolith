        scope.Complete();

        _logger.LogInformation("Successfully processed {Operation}", nameof(Controller8));
        return new Controller8Result { Success = true, Data = entity };
    }
    catch (DbUpdateConcurrencyException ex)
    {
        _logger.LogError(ex, "Concurrency conflict processing {Operation}", nameof(Controller8));
        return new Controller8Result { Success = false, ErrorCode = "CONCURRENCY_CONFLICT" };
    }
