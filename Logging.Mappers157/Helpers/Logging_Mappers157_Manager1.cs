/// Gets or creates a cached Manager1 instance.
/// Uses IMemoryCache with sliding expiration.
/// </summary>
public async Task<Manager1Data> GetCachedManager1Async(string key)
{
    var cacheKey = $"Manager1_{key}";

    if (_cache.TryGetValue(cacheKey, out Manager1Data cached))
    {
        _logger.LogDebug("Cache hit for {Key}", cacheKey);
        return cached;
    }

    _logger.LogDebug("Cache miss for {Key}, loading from source", cacheKey);

    var data = await LoadFromManager1SourceAsync(key);

    var cacheOptions = new MemoryCacheEntryOptions()
        .SetSlidingExpiration(_cacheDuration)
