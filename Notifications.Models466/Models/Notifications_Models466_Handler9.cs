    if (_cache.TryGetValue(cacheKey, out Handler9Data cached))
    {
        _logger.LogDebug("Cache hit for {Key}", cacheKey);
        return cached;
    }

    _logger.LogDebug("Cache miss for {Key}, loading from source", cacheKey);

    var data = await LoadFromHandler9SourceAsync(key);

